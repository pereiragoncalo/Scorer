def glyph(char,display=False):
    text=unicodedata.normalize('NFD',char)
    base=SPECIAL.get(text[0],PUNCT.get(text[0],text[0]))
    pattern=(ART.get(base.upper()) if display else LOWER.get(base) or ART.get(base))
    if pattern is None:return None
    pen=TTGlyphPen(None)
    scale_x=.86 if display else 1
    def cell(x,y,mark=False):
        step=105;inset=0
        x0=(55+x*step+inset)*scale_x;y0=y*step+inset
        x1=(55+(x+1)*step-inset)*scale_x;y1=(y+1)*step-inset
        slant=.10 if display else 0
        pen.moveTo((x0+slant*y0,y0));pen.lineTo((x0+slant*y1,y1));pen.lineTo((x1+slant*y1,y1));pen.lineTo((x1+slant*y0,y0));pen.closePath()
    for row,bits in enumerate(pattern.split('/')):
        for x,bit in enumerate(bits):
            if bit=='1':cell(x,6-row)
    for j,mark in enumerate(text[1:]):
        if mark in ('\u0323','\u0327','\u0328'):
            cell(2,-1)
            if mark!='\u0323':cell(1,-2)
        else:
            for x,y in MARKS.get(mark,[(2,1)]):cell(x,8+y+j*2,True)
    return pen.glyph()


def build(path,display=False):
    chars=set(chr(i) for i in range(32,127))|set(chr(i) for i in range(0xa0,0x250))|set(chr(i) for i in range(0x1e00,0x1f00))|set(PUNCT)
    glyphs={};cmap={}
    for char in sorted(chars):
        result=glyph(char,display)
        if result is not None:
            name=f'uni{ord(char):04X}';glyphs[name]=result;cmap[ord(char)]=name
    glyphs['.notdef']=glyph('?',display)
    order=['.notdef']+sorted(n for n in glyphs if n!='.notdef')
    fb=FontBuilder(1000,isTTF=True);fb.setupGlyphOrder(order);fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs);fb.setupHorizontalMetrics({g:(650 if display else 680,35) for g in order})
    fb.setupHorizontalHeader(ascent=1155,descent=-210,lineGap=0)
    family='Scorer Press Display' if display else 'Scorer Press Pixel'
    fb.setupNameTable(dict(familyName=family,styleName='Regular',uniqueFontIdentifier=family+' 1.0',fullName=family,psName=family.replace(' ',''),version='Version 1.0'))
    fb.setupOS2(sTypoAscender=1155,sTypoDescender=-210,sTypoLineGap=0,usWinAscent=1450,usWinDescent=210)
    fb.setupPost();fb.setupMaxp();fb.setupHead(created=3866140800,modified=3866140800)
    fb.font.recalcTimestamp=False;fb.font.save(path)


